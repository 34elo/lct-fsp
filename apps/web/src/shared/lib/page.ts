/**
 * Сетка страниц. Каркас (`PageContainer`) даёт максимум 1440 без полей; каждая страница
 * берёт одну из трёх ширин и общий ритм: поля 16/24, промежутки между блоками 16 (`gap-4`).
 * Вертикальный ритм — 8/16/24/32: `gap-2` внутри блока, `gap-4` между блоками, `gap-6` между секциями, `gap-8` между зонами.
 */
const BASE = "mx-auto flex w-full flex-col gap-4 px-4 py-4 md:px-6 md:py-6";

export const PAGE = {
  /** Узкая: формы, одиночные карточки, текст (768). */
  narrow: `${BASE} max-w-3xl`,
  /** Обычная: списки, карточки, кабинеты (1328, как макеты v2). */
  normal: `${BASE} max-w-[1328px]`,
  /** Широкая: таблицы и админские экраны (во всю ширину каркаса). */
  wide: BASE,
} as const;

export type PageWidth = keyof typeof PAGE;
